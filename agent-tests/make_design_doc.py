"""Writes docs/STAGE3_TEST_DESIGN.md from cases.py, so the test design and the tests agree.

    python agent-tests/make_design_doc.py
"""
from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

from cases import CASES, REQUIREMENTS

OUT = Path(__file__).resolve().parent.parent / "docs" / "STAGE3_TEST_DESIGN.md"

# section 17 of the project instructions: which tests cover each kind of challenging situation
CHALLENGES = [
    ("Ambiguous requests", ["ambiguous"]), ("Incomplete information", ["incomplete"]),
    ("Invalid inputs", ["invalid"]), ("Unavailable tools", ["fault (unavailable tool)"]),
    ("Conflicting instructions", ["conflicting"]), ("Irrelevant information", ["irrelevant"]),
    ("Malformed responses / unexpected tool outputs", ["adversarial (malformed ids)"]), ("Long conversations", ["long conversation"]),
    ("Repeated requests", ["repeated"]), ("Edge cases", ["edge"]),
    ("Adversarial or misleading inputs", ["adversarial", "adversarial (prompt injection)", "misleading"]),
]


def describe_input(case) -> str:
    parts = []
    for step in case.steps:
        if step.get("request"):
            parts.append(f'{step["action"]}: "{step["request"]}"')
        else:
            parts.append(json.dumps(step))
    return " → ".join(parts)


def main() -> None:
    by_req = defaultdict(list)
    for case in CASES:
        by_req[case.requirement].append(case.id)
    lines = [
        "# SmartPlate — Stage 3 agent behavioural requirements and KUMA test design", "",
        "*Generated by `agent-tests/make_design_doc.py` from `agent-tests/cases.py`; edit the cases, "
        "not this file.*", "",
        "The AI agent behind F04 (recommend), F05 (weekly plan) and F06 (edit plan) is tested with KUMA "
        "(`kuma-defuzex`) running fully locally: a custom Case Provider gives KUMA each case's steps, "
        "the harness sends every step to a fresh `java -jar smartplate.jar --json` session, and a custom "
        "Judge evaluates the replies. The judge uses its own food rules (`agent-tests/checks.py`), not "
        "the agent's `ConstraintValidator`, so a gap in the agent's validator shows up as a failure "
        "instead of being repeated by the test.", "",
        "## Behavioural requirements", "",
        "| ID | Requirement | Expected behaviour | Tests |", "|---|---|---|---|"]
    for br, (name, text) in REQUIREMENTS.items():
        tests = ", ".join(by_req.get(br, [])) or "checked inside other tests"
        lines.append(f"| {br} | {name} | {text} | {tests} |")
    lines += ["", "BR-09 (transparency) is checked in every test whose AI step succeeds; BR-08 checks "
              "are *minor* issues, all others *major*.", "",
              "## Challenging situations covered (instructions §17)", "",
              "| Situation | Tests |", "|---|---|"]
    for name, kinds in CHALLENGES:
        ids = [c.id for c in CASES if c.kind in kinds]
        lines.append(f"| {name} | {', '.join(ids) or '-'} |")
    lines += ["", "A malformed *LLM* answer (no ids, unknown ids, wrong format) cannot be forced on a real "
              "model, so it is also covered deterministically by the JUnit tests in "
              "`MealPlanningAgentTest`, which script the Mock AI's answers.", "", "## Test cases", ""]
    for case in CASES:
        lines += [f"### {case.id} — {case.title}", "",
                  "| Field | Description |", "|---|---|",
                  f"| Test ID | {case.id} ({case.kind}) |",
                  f"| Requirement | {case.requirement} — {REQUIREMENTS[case.requirement][0]} |",
                  f"| Input | {describe_input(case)} |",
                  f"| Context | {case.context} |",
                  f"| Expected behaviour | {case.expected} |",
                  f"| Prohibited behaviour | {case.prohibited} |",
                  f"| Evaluation | {case.evaluation} |", ""]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
